export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // storage unavailable
  }
}

export function loadLocale(): Locale {
  try {
    const htmlLang = document.documentElement.lang;
    if (htmlLang === 'uk' || htmlLang === 'de' || htmlLang === 'en') {
      currentLocale = htmlLang;
      localStorage.setItem(STORAGE_KEY, htmlLang);
      return currentLocale;
    }
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'uk' || stored === 'de' || stored === 'en') {
      currentLocale = stored;
      return stored;
    }
  } catch {
    // fallback to en
  }
  return currentLocale;
}

export function t(key: string, params?: Record<string, string | number>): string {
  const dict = DICT[currentLocale];
  let val = dict[key];
  if (!val) {
    val = DICT.en[key] ?? key;
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      val = val.replace(`{${k}}`, String(v));
    }
  }
  return val;
}

export function applyI18n(root: ParentNode = document): void {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && 'placeholder' in el) (el as HTMLInputElement).placeholder = t(key);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });
}
